// Shared OpenAPI components (SPEC §1, §7.3): problem details and error codes, the generic error
// responses, the X-Request-Id header, pagination parameters and the id formats. Routes reference
// them with the helpers here; openapi.ts registers them on every app.
import { CursorParamSchema, ERROR_CODES, ErrorCodeSchema, ID_SCHEMA_NAMES, ID_SCHEMAS, LimitParamSchema, NextCursorSchema, ProblemDetailsSchema, type ErrorCode, type IdPrefix } from '@flussctrl/core'
import type { OpenAPIHono } from '@hono/zod-openapi'
import type { z } from 'zod'
import type { AppEnv } from './app-env.ts'

// Core's schemas are plain Zod: core does not depend on Hono, and names its components with
// `.meta({ id })`. The registry calls `.openapi()` on what it registers, a method @hono/zod-openapi
// adds to Zod instances created after it loads; core's schemas may predate that, so register a
// clone (same definition and metadata) instead.
function component<T extends z.ZodType> (schema: T): T {
  return schema.clone() as T
}

/** The generic errors any endpoint can return (SPEC §7.3 "Before a command exists", §21.5). */
export const SHARED_ERROR_RESPONSES = {
  unauthorised: 'Unauthorised',
  insufficient_scope: 'InsufficientScope',
  not_found: 'NotFound',
  validation_failed: 'ValidationFailed',
  rate_limited: 'RateLimited',
  internal_error: 'InternalError',
  service_unavailable: 'ServiceUnavailable',
} as const satisfies Partial<Record<ErrorCode, string>>

export type SharedErrorCode = keyof typeof SHARED_ERROR_RESPONSES

const REQUEST_ID_HEADER = 'X-Request-Id'

/** Every response carries X-Request-Id (SPEC §1). Use as a response's `headers`. */
export const requestIdHeader = { [REQUEST_ID_HEADER]: { $ref: `#/components/headers/${REQUEST_ID_HEADER}` } }

/** A `$ref` to the shared response for a generic error code. */
export function problemResponseRef (code: SharedErrorCode): { $ref: string } {
  return { $ref: `#/components/responses/${SHARED_ERROR_RESPONSES[code]}` }
}

/** Registers the shared components. Called once per app, before the document is generated. */
export function registerComponents (app: OpenAPIHono<AppEnv>): void {
  const registry = app.openAPIRegistry

  registry.registerComponent('headers', REQUEST_ID_HEADER, {
    description: 'Generated by the API for every request (`req_` + UUIDv7); a value sent by the caller is ignored. Quote it when reporting a problem.',
    required: true,
    schema: { $ref: '#/components/schemas/RequestId' },
  })

  for (const [prefix, schema] of Object.entries(ID_SCHEMAS) as Array<[IdPrefix, z.ZodType]>) {
    registry.register(ID_SCHEMA_NAMES[prefix], component(schema))
  }
  registry.register('ErrorCode', component(ErrorCodeSchema))
  registry.register('ProblemDetails', component(ProblemDetailsSchema))
  registry.register('NextCursor', component(NextCursorSchema))
  registry.registerParameter('Limit', component(LimitParamSchema))
  registry.registerParameter('Cursor', component(CursorParamSchema))

  for (const [code, name] of Object.entries(SHARED_ERROR_RESPONSES) as Array<[SharedErrorCode, string]>) {
    const def = ERROR_CODES[code]
    registry.registerComponent('responses', name, {
      description: `\`${def.status} ${code}\`: ${def.title}.`,
      headers: {
        ...requestIdHeader,
        ...(code === 'rate_limited'
          ? { 'Retry-After': { description: 'Seconds to wait before retrying.', required: true, schema: { type: 'integer', minimum: 0 } } }
          : {}),
      },
      content: { 'application/problem+json': { schema: { $ref: '#/components/schemas/ProblemDetails' } } },
    })
  }
}
